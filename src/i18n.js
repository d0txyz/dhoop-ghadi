function period(hour) {
  if (hour >= 4 && hour < 12) return 0;
  if (hour >= 12 && hour < 16) return 1;
  if (hour >= 16 && hour < 20) return 2;
  return 3;
}

/** A clock hour (0 to 24) in the way people say it: "5 am", "सुबह 5 बजे". */
export function sayHour(lang, hour, form = 'hourWord') {
  const h24 = hour % 24;
  const h12 = h24 % 12 === 0 ? 12 : h24 % 12;
  const table = T[lang] || T.en;
  if (!table.hourWord) {
    if (h24 === 12) return '12 noon';
    if (h24 === 0) return '12 midnight';
    return `${h12} ${h24 < 12 ? 'am' : 'pm'}`;
  }
  const pattern = table[form] || table.hourWord;
  return pattern.replace('{p}', table.periods[period(h24)]).replace('{h}', String(h12));
}

/** "5 am to 9 am", "सुबह 5 से सुबह 9 बजे तक". */
export function sayRange(lang, start, end) {
  return t(lang, 'range', { a: sayHour(lang, start, 'rangeA'), b: sayHour(lang, end, 'rangeB') });
}
